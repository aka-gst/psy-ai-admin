// Границы безопасности намеренно живут в коде, а не в редактируемом каталоге
// контента: владелец сайта меняет тексты ответов, но не то, какие сообщения
// считаются кризисными или медицинскими.
//
// Кризисный набор настроен на полноту, а не на точность. Лишний показ телефона
// экстренной службы стоит человеку нескольких секунд; пропущенное сообщение
// стоит несравнимо дороже. Ложные срабатывания удерживаются контрольным
// набором вопросов в eval/cases/controls.json.
//
// Правила первого прототипа сохранены дословно и идут первыми: каждый
// следующий список только расширяет их, поэтому ни одно прежде распознанное
// сообщение не может перестать распознаваться.
//
// В JavaScript \w не покрывает кириллицу, поэтому основы слов расширяются
// явным классом [а-я] — иначе «наврежу себе» не совпадёт с основой «навре».

const normalise = (input) =>
  String(input)
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^а-яa-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

// Допуск в несколько слов между глаголом и объектом: «причинить вред себе».
const gap = "( [а-я]+){0,2}";

const LEGACY_CRISIS = /самоуб|суицид|убить себя|покончить с собой|причинить.*себе|не хочу жить|навредить.*(себе|друг)/;

// Прямое называние: одного совпадения достаточно.
const LETHAL_INTENT = [
  /суицид/,
  /самоуби[йв]/,
  /покончить (с )?(собой|жизнью)/,
  /уйти из жизни/,
  /свести счеты/,
  /покончить с (этим|всем)/,
  /наложить на себя руки/,
  /лишить себя жизни/,
];

// Намерение причинить вред себе или близкому: основа глагола плюс объект.
const SELF_HARM = [
  new RegExp(`(навре|повре|причин|поре|реж|калеч|ранит)[а-я]*${gap} (себе|себя)`),
  new RegExp(`(навре|повре|причин|калеч)[а-я]*${gap} (друг|близк|ребенк|сестр|брат)`),
  /вредить себе/,

];

// Безнадёжность и желание смерти, сформулированные обиходной речью.
const HOPELESSNESS = [
  /не хоч(у|ет|ется) (больше )?жить/,
  /(незачем|не зачем|нет смысла|не вижу смысла)( дальше| больше)* (жить|существовать|продолжать)/,
  /уйти навсегда/,
  // «не могу жить без …» — оборот речи, а не намерение: контроль ct-06.
  /не могу (больше |так |дальше )*жить(?! без)/,
  /не вижу выхода/,
  /жизнь потеряла смысл/,
  /нет сил (больше )?(жить|терпеть)/,
  /хочу (просто )?исчезнуть/,
  /(хочу|хочется) (просто )?уйти (навсегда|насовсем)/,
  /(хочу|хочет|хотят|хочется) умереть/,
  /устал[а-я]* жить/,
  /не хочу (больше )?просыпаться/,
  /незачем просыпаться/,
  /сделать себе (больно|плохо)/,
  /(перестать|хватит) (жить|существовать)/,
  /лучше бы меня не было/,
  /(все|всё) безнадежно/,
  // Только как самостоятельная жалоба: «не выдержу трёхчасовое занятие» —
  // обычный вопрос про перерывы, а не сигнал риска.
  /не выдержу( больше| это| этого| уже)?$/,
  /(хочу|думаю|решил[а-я]*) (просто |уже )?(все )?(закончить|покончить)( все| это)?$/,
  /(хочу|думаю|решил[а-я]*) (просто |уже )?(все )?(закончить|покончить) (все|это)/,
];

const LEGACY_CLINICAL = /диагноз|паническ|тревог|депрес|антидепресс|лекарств|таблетк|травм|лечи(ть|те)|терапи|упражнен/;

// Медицинская и терапевтическая зона: администратор в неё не заходит.
const CLINICAL = [
  /диагност/,
  /пани[кч]/,
  /тревож/,
  /препарат/,
  /дыхательн/,
  /расстройств|биполяр|шизофрен|обсесс|невроз|бессонниц|самоповрежд/,
  /(^| )(птср|рпп|сдвг)( |$)/,
  /психиатр|симптом/,
  /успокоительн|снотворн|транквилизат/,
  /выгорани/,
  /(^| )лечени/,
  /фоби/,
  /навязчив/,
  new RegExp(`(попить|пить|принимать|выпить)[а-я]*${gap} (от|при) (нерв|тревог|стресс|бессонниц|депресс|паник)`),
];

const matches = (patterns, text) => patterns.some((pattern) => pattern.test(text));

export function isCrisis(input) {
  const text = normalise(input);
  return LEGACY_CRISIS.test(text) || matches(LETHAL_INTENT, text) || matches(SELF_HARM, text) || matches(HOPELESSNESS, text);
}

export function isClinical(input) {
  const text = normalise(input);
  return LEGACY_CLINICAL.test(text) || matches(CLINICAL, text);
}

export const signalGroups = { LEGACY_CRISIS, LETHAL_INTENT, SELF_HARM, HOPELESSNESS, LEGACY_CLINICAL, CLINICAL };

// Мягкая страховка на случай, когда кризис не распознан. Списки выше не
// покрывают живую речь: каждый новый набор перефразировок находит примерно
// столько же промахов, сколько предыдущий. Поэтому сообщение, которое не
// удалось отнести ни к одной теме центра и при этом звучит как рассказ о себе
// и о плохом, получает ответ с экстренными контактами — без утверждения, что
// это кризис.
const FIRST_PERSON = /(^| )(я|мне|меня|мной|мой|моя|мои)( |$)|[а-я]+(юсь|усь|аюсь|яюсь)( |$)/;
const NEGATIVE = /(не могу|не хочу|не вижу|тяжел|плохо|больно|страшно|одинок|устал|невыносим|нет сил|никто|бессмысл|незачем|беспокой|тревож|пуст[оы]|сдаюсь|конец)/;

export function isPossibleDistress(input) {
  const text = normalise(input);
  return FIRST_PERSON.test(text) && NEGATIVE.test(text);
}
