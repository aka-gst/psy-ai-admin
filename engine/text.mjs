// Нормализация русского текста для поиска. Полноценная морфология сюда не
// тянется: движок обязан работать без зависимостей и внутри Cloudflare Worker.
// Вместо неё — отсечение частых окончаний и обрезка основы до пяти символов.
// Это грубо («аренда» и «арендовать» сводятся к «аренд» только после обрезки),
// но для набора из десятка коротких документов даёт нужную полноту.

const SUFFIXES = [
  "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими", "ешь", "ете",
  "ают", "яют", "ует", "ах", "ях", "ов", "ев", "ий", "ый", "ая", "яя", "ое",
  "ее", "ые", "ие", "ам", "ям", "ом", "ем", "ой", "ей", "ую", "юю", "ут", "ют",
  "ат", "ят", "ла", "ло", "ли", "ть", "ся", "сь",
  "а", "я", "о", "е", "и", "ы", "у", "ю", "й", "ь",
];

// Вопросительные и служебные слова ничего не различают между страницами.
const STOPWORDS = new Set([
  "как", "что", "где", "когда", "сколько", "какой", "какие", "какая", "какое",
  "можно", "нужно", "ли", "есть", "быть", "вы", "ваш", "ваши", "вашего", "мне",
  "мой", "моя", "мои", "меня", "это", "этот", "эта", "так", "уже", "еще",
  "или", "но", "же", "бы", "то", "все", "весь", "для", "про", "над", "под",
  "из", "от", "до", "по", "на", "об", "при", "не", "ни", "их", "его", "ее",
  "хочу", "хотел", "хотела", "надо", "буду", "если", "чтобы", "тоже", "очень",
  "вас", "нас", "вам", "нам", "там", "тут", "вот", "который", "которые",
  "такой", "такая", "такое", "такие", "этом", "этой", "него", "нее", "них",
  "без", "свои", "своих", "себе", "себя", "тебе", "вами", "нами", "быть",
]);

export const normalise = (input) =>
  String(input)
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^а-яa-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

export function stem(word) {
  let value = word;
  for (const suffix of SUFFIXES) {
    if (value.length - suffix.length >= 3 && value.endsWith(suffix)) {
      value = value.slice(0, -suffix.length);
      break;
    }
  }
  return value.slice(0, 5);
}

export function tokenize(input) {
  return normalise(input)
    .split(" ")
    .filter((word) => word.length > 2 && !STOPWORDS.has(word))
    .map(stem);
}
